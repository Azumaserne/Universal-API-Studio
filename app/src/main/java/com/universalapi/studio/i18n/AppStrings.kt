enum class AppLanguage(
    val code: String,
    val nativeName: String,
    val welcomeWord: String,
) {
    ZH_CN("zh-CN", "简体中文", "欢迎"),
    EN("en", "English", "Welcome"),
    ZH_HK("zh-HK", "粵語", "歡迎"),
    JA("ja", "日本語", "ようこそ"),
    KO("ko", "한국어", "환영합니다"),
    DE("de", "Deutsch", "Willkommen"),
    FR("fr", "Français", "Bienvenue"),
    ES("es", "Español", "Bienvenido");

    companion object {
        fun fromCode(code: String?): AppLanguage? =
            entries.firstOrNull { it.code.equals(code, ignoreCase = true) }

        fun fromSystemLocale(): AppLanguage {
            val locale = Locale.getDefault()
            val lang = locale.language.lowercase()
            val country = locale.country.uppercase()
            val script = locale.script.lowercase()
            return when {
                lang == "zh" && (country in setOf("HK", "MO", "TW") || script == "hant") -> ZH_HK
                lang == "zh" -> ZH_CN
                lang == "en" -> EN
                lang == "ja" -> JA
                lang == "ko" -> KO
                lang == "de" -> DE
                lang == "fr" -> FR
                lang == "es" -> ES
                else -> ZH_CN
            }
        }
    }
}

